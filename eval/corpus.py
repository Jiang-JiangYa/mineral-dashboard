def records():
    return [
        Record(
            kind="policy",
            source="Australia DISR",
            url=BASE + slug,
            title=title,
            text=text,
            published_at="2023-07-07T00:00:00+00:00",
            countries=["AU"],
            is_reference=True,
            publisher="Department of Industry, Science and Resources",
            document_type="translated_reference_summary",
        )
        for slug, title, text, _, _ in REFERENCES
    ]


def bootstrap(store):
    result = {}
    for record in records():
        status = store.upsert(record)["status"]
        result[status] = result.get(status, 0) + 1
    return result
